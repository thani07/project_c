import sharp from "sharp";
import fs from "node:fs";
const manifest = JSON.parse(fs.readFileSync("scripts/images.manifest.json", "utf8"));
const credits = JSON.parse(fs.readFileSync("scripts/credits.json", "utf8"));
const out = {};
for (const [key, [title]] of Object.entries(manifest)) {
  const file = `public/images/${key}.jpg`;
  if (!fs.existsSync(file)) continue;
  const { width, height } = await sharp(file).metadata();
  const c = credits[title.replace(/ /g, " ")] ?? credits[title] ?? {};
  out[key] = { src: `/images/${key}.jpg`, width, height, title, author: c.author ?? "", license: c.license ?? "", licenseUrl: c.licenseUrl ?? "", page: c.page ?? "" };
}
fs.writeFileSync("src/data/image-files.generated.ts",
`// Generated by scripts/build-image-data.mjs. Do not edit by hand.
export const imageFiles = ${JSON.stringify(out, null, 2)} as const;
export type ImageKey = keyof typeof imageFiles;
`);
console.log(Object.keys(out).length, "images");
